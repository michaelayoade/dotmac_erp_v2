"""Leases (IFRS 16 lessee core) — ERP-unique slice 11.

Contract + liability + right-of-use asset + payment schedule. The
schedule is generated by annuity math from the contract terms
(present value at the discount rate, interest/principal split per
period); journal consequences post through dotmac-accounting via
opaque refs. Modifications and index remeasurement are named
rehearsal work, not silently approximated here.
"""

