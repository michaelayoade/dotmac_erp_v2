class LeaseError(RuntimeError):
    """A lease rule refusal."""


def _add_months(day: date, months: int) -> date:
    """Calendar month addition clamped to month end (Jan 31 + 1mo -> Feb 28)."""

    total = (day.year * 12 + day.month - 1) + months
    year, month0 = divmod(total, 12)
    month = month0 + 1
    last = calendar.monthrange(year, month)[1]
    return date(year, month, min(day.day, last))


def present_value(payment: Decimal, annual_rate: Decimal, periods: int, per_year: int) -> Decimal:
    """PV of a level annuity in arrears, Decimal throughout."""

    if periods < 1:
        raise LeaseError("periods must be positive")
    r = annual_rate / Decimal(per_year)
    if r == 0:
        return (payment * periods).quantize(_CENT, rounding=ROUND_HALF_UP)
    discount = (Decimal(1) + r) ** (-periods)
    return (payment * (Decimal(1) - discount) / r).quantize(_CENT, rounding=ROUND_HALF_UP)


def commence_lease(session: Session, *, tenant_id: UUID, lease_id: UUID) -> LeaseLiability:
    """Activate a draft lease: liability + ROU asset + full schedule."""

    lease = session.scalar(
        select(LeaseContract).where(LeaseContract.tenant_id == tenant_id, LeaseContract.id == lease_id)
    )
    if lease is None:
        raise LeaseError("lease contract not found")
    if lease.status != "draft":
        raise LeaseError(f"lease is {lease.status!r}, not draft")
    if lease.payment_frequency_months < 1 or lease.lease_term_months % lease.payment_frequency_months:
        raise LeaseError("lease term must divide evenly by payment frequency")
    periods = lease.lease_term_months // lease.payment_frequency_months
    per_year = 12 // lease.payment_frequency_months
    pv = present_value(lease.base_payment_amount, lease.discount_rate, periods, per_year)
    liability = LeaseLiability(
        tenant_id=tenant_id,
        lease_id=lease.id,
        initial_liability_amount=pv,
        discount_rate=lease.discount_rate,
        current_balance=pv,
    )
    session.add(liability)
    rou_value = pv + lease.initial_direct_costs
    session.add(
        LeaseRouAsset(
            tenant_id=tenant_id,
            lease_id=lease.id,
            initial_value=rou_value,
            useful_life_months=lease.lease_term_months,
            carrying_amount=rou_value,
        )
    )
    r = lease.discount_rate / Decimal(per_year)
    balance = pv
    for number in range(1, periods + 1):
        interest = (balance * r).quantize(_CENT, rounding=ROUND_HALF_UP)
        principal = lease.base_payment_amount - interest
        if number == periods:
            principal = balance
            total = principal + interest
        else:
            total = lease.base_payment_amount
        closing = balance - principal
        session.add(
            LeasePayment(
                tenant_id=tenant_id,
                lease_id=lease.id,
                payment_number=number,
                payment_date=_add_months(lease.commencement_date, number * lease.payment_frequency_months),
                total_payment=total,
                principal_portion=principal,
                interest_portion=interest,
                opening_balance=balance,
                closing_balance=closing,
            )
        )
        balance = closing
    lease.status = "active"
    session.flush()
    return liability


def record_payment(session: Session, *, tenant_id: UUID, payment_id: UUID, paid_on: date) -> LeasePayment:
    """Settle the next scheduled payment; out-of-order payment refused."""

    payment = session.scalar(
        select(LeasePayment).where(LeasePayment.tenant_id == tenant_id, LeasePayment.id == payment_id)
    )
    if payment is None:
        raise LeaseError("lease payment not found")
    if payment.status != "scheduled":
        raise LeaseError(f"payment is {payment.status!r}, not scheduled")
    earlier_open = session.scalar(
        select(LeasePayment).where(
            LeasePayment.tenant_id == tenant_id,
            LeasePayment.lease_id == payment.lease_id,
            LeasePayment.payment_number < payment.payment_number,
            LeasePayment.status == "scheduled",
        )
    )
    if earlier_open is not None:
        raise LeaseError("an earlier scheduled payment is still open")
    liability = session.scalar(
        select(LeaseLiability).where(LeaseLiability.tenant_id == tenant_id, LeaseLiability.lease_id == payment.lease_id)
    )
    if liability is None:
        raise LeaseError("lease liability not found")
    payment.status = "paid"
    payment.is_paid = True
    payment.actual_payment_date = paid_on
    liability.current_balance = payment.closing_balance
    liability.total_interest_expense += payment.interest_portion
    liability.total_payments_made += payment.total_payment
    session.flush()
    return payment


