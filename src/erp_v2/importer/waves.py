# Tables already living in module storage carry; everything else is a
# transform whose column-level spec is pending its wave rehearsal.
_CARRY: Final = frozenset({"stored_files", "platform_stored_files"})


def build_wave_mappings() -> tuple[TableMapping, ...]:
    """Expand the census into planner mappings (all transforms blocked)."""

    mappings: list[TableMapping] = []
    for destination, tables in SOURCE_TABLES.items():
        for table in tables:
            if table in _CARRY:
                mappings.append(
                    TableMapping(
                        source=f"mod_files.{table}",
                        destination=f"mod_files.{table}",
                        kind="carry",
                    )
                )
            elif destination == "retire":
                mappings.append(TableMapping(source=f"public.{table}", destination="retire", kind="retire"))
            else:
                mappings.append(
                    TableMapping(
                        source=f"public.{table}",
                        destination=destination,
                        kind="transform",
                        needs_ruling="column-level transform spec pending wave rehearsal",
                    )
                )
    return tuple(mappings)


